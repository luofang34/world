/// One `double name[..]..` definition of the C file.
struct Array<'a> {
    name: &'a str,
    /// The row length of a two-dimensional array.
    columns: Option<usize>,
    values: Vec<&'a str>,
}

/// The C file with its comments removed.
fn without_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some((before, after)) = rest.split_once("/*") {
        out.push_str(before);
        rest = after.split_once("*/").map_or("", |(_, tail)| tail);
    }
    out.push_str(rest);
    out
}

/// Every array definition of the comment-free C text, in file order.
fn arrays(text: &str) -> Result<Vec<Array<'_>>, XtaskError> {
    let malformed = |problem: String| XtaskError::Malformed {
        file: DATA,
        problem,
    };
    let mut found = Vec::new();
    for definition in text.split("double ").skip(1) {
        let (declaration, body) = definition
            .split_once('=')
            .ok_or_else(|| malformed("an array has no initializer".to_owned()))?;
        let body = body.split_once(';').map_or(body, |(values, _)| values);
        let mut dimensions = declaration.split('[');
        let name = dimensions.next().unwrap_or_default().trim();
        let sizes: Vec<usize> = dimensions
            .filter_map(|size| size.trim().trim_end_matches(']').parse().ok())
            .collect();
        let values: Vec<&str> = body
            // The file continues some rows with a backslash.
            .split(|c: char| matches!(c, ',' | '{' | '}' | '\\') || c.is_whitespace())
            .filter(|token| !token.is_empty())
            .collect();
        if let Some(bad) = values.iter().find(|token| token.parse::<f64>().is_err()) {
            return Err(malformed(format!("{name} holds a non-number `{bad}`")));
        }
        let columns = match sizes.as_slice() {
            [_] => None,
            [rows, columns] if rows * columns == values.len() => Some(*columns),
            _ => return Err(malformed(format!("{name} does not fill its dimensions"))),
        };
        found.push(Array {
            name,
            columns,
            values,
        });
    }
    Ok(found)
}

fn write_rows(out: &mut String, values: &[&str], indent: &str) {
    for line in values.chunks(VALUES_PER_LINE) {
        // Writing to a String cannot fail.
        writeln!(out, "{indent}{},", line.join(", ")).ok();
    }
}

/// The Rust source of `module`, from the arrays of the C file.
fn render(module: &Module, arrays: &[Array<'_>]) -> Result<String, XtaskError> {
    let mut out = format!(
        "//! {}\n//!\n//! Generated by `cargo run -p xtask -- gen-msis` from the data file\n//! [`crate::NRLMSISE00`]'s provenance names; that provenance carries the\n//! file's checksum. Indices are zero-based, as in that file.\n",
        module.heading
    );
    for (source, constant, doc) in module.arrays {
        let array = arrays
            .iter()
            .find(|array| array.name == *source)
            .ok_or_else(|| XtaskError::Malformed {
                file: DATA,
                problem: format!("no array `{source}`"),
            })?;
        writeln!(out, "\n/// {doc}\n#[rustfmt::skip]").ok();
        match array.columns {
            None => {
                let len = array.values.len();
                writeln!(out, "pub(crate) const {constant}: [f64; {len}] = [").ok();
                write_rows(&mut out, &array.values, "    ");
            }
            Some(columns) => {
                let rows = array.values.len() / columns;
                writeln!(
                    out,
                    "pub(crate) const {constant}: [[f64; {columns}]; {rows}] = ["
                )
                .ok();
                for row in array.values.chunks(columns) {
                    out.push_str("    [\n");
                    write_rows(&mut out, row, "        ");
                    out.push_str("    ],\n");
                }
            }
        }
        out.push_str("];\n");
    }
    Ok(out)
}

/// Each generated module's path and source, from the C data file's text.
pub(crate) fn generate(data: &str) -> Result<Vec<(&'static str, String)>, XtaskError> {
    let text = without_comments(data);
    let arrays = arrays(&text)?;
    MODULES
        .iter()
        .map(|module| Ok((module.path, render(module, &arrays)?)))
        .collect()
}

/// Fails unless `data` is the file `provenance` names by checksum and
/// `tables(path)` is exactly what it generates for every module.
pub(crate) fn verify(
    data: &[u8],
    provenance: &str,
    tables: &dyn Fn(&'static str) -> Result<String, XtaskError>,
) -> Result<(), XtaskError> {
    let recorded = provenance
        .split_once(CHECKSUM_FIELD)
        .and_then(|(_, rest)| rest.split_once('"'))
        .map(|(sha, _)| sha.to_owned())
        .ok_or_else(|| XtaskError::NoRecordedChecksum {
            path: PathBuf::from(PROVENANCE),
        })?;
    let actual = hex(&Sha256::digest(data));
    if recorded != actual {
        return Err(XtaskError::ChecksumMismatch {
            file: DATA,
            recorded,
            actual,
        });
    }
    let text = std::str::from_utf8(data).map_err(|_| XtaskError::NotText {
        path: PathBuf::from(DATA),
    })?;
    for (path, generated) in generate(text)? {
        if tables(path)? != generated {
            return Err(XtaskError::TableDiffers {
                path: PathBuf::from(path),
                file: DATA,
                regenerate: "gen-msis",
            });
        }
    }
    Ok(())
}

/// `check-msis` over the committed files.
pub(crate) fn check(root: &Path) -> Result<(), XtaskError> {
    verify(&read(root, DATA)?, &read_text(root, PROVENANCE)?, &|path| {
        read_text(root, path)
    })
}

/// `gen-msis`: rewrite the tables from the committed file.
pub(crate) fn write(root: &Path) -> Result<(), XtaskError> {
    let data = read_text(root, DATA)?;
    for (relative, generated) in generate(&data)? {
        let path = root.join(relative);
        std::fs::write(&path, generated).map_err(|source| XtaskError::Io {
            action: "writing",
            path,
            source,
        })?;
    }
    Ok(())
}

