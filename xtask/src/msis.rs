//! The NRLMSISE-00 coefficient tables and the file they are generated from.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

use crate::error::XtaskError;
use crate::files::{hex, read, read_text};

const DATA: &str = "crates/world-thermosphere/data/nrlmsise-00_data.c";
const PROVENANCE: &str = "crates/world-thermosphere/src/nrlmsise00.rs";
const CHECKSUM_FIELD: &str = "source_sha256: \"";
const VALUES_PER_LINE: usize = 5;

/// One generated module: its path, its heading and the arrays it holds,
/// each as `(name in the C file, generated constant, doc line)`.
struct Module {
    path: &'static str,
    heading: &'static str,
    arrays: &'static [(&'static str, &'static str, &'static str)],
}

